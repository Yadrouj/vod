import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const origin = process.env.LOAD_BASE_URL || 'http://localhost:3004';
assert.ok(['localhost', '127.0.0.1'].includes(new URL(origin).hostname));
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true, timeout: 15000 });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
  page.setDefaultNavigationTimeout(90000); page.setDefaultTimeout(30000);
  await page.route('**/*', route => route.request().url().startsWith(origin) ? route.continue() : route.abort());
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin}/tt0111161`, { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(2000);
  const list = page.locator('.movie-file-list');
  assert.equal(await list.locator('.movie-file-row').count(), 0);
  const dubbed = list.getByRole('button', { name: 'دوبله فارسی', exact: true });
  await dubbed.click();
  await list.getByRole('button', { name: '1080p', exact: true }).waitFor();
  const qualities = await list.locator('fieldset').nth(1).getByRole('button').allTextContents();
  assert.deepEqual(qualities.slice(0, 3), ['1080p', '720p', '480p']);
  await list.getByRole('button', { name: '1080p', exact: true }).click();
  await list.locator('.movie-file-row').first().waitFor();
  const rows = await list.locator('.file-info strong').allTextContents();
  assert.ok(rows.every(text => text.includes('1080p') && text.includes('دوبله فارسی')));
  await page.goto(`${origin}/tt0903747`, { waitUntil: 'domcontentloaded' });
  const episode = page.locator('.episode-row').filter({ has: page.locator('summary') }).first();
  await episode.locator('summary').click();
  await episode.locator('fieldset').first().getByRole('button').first().click();
  await episode.locator('fieldset').nth(1).waitFor();
  await episode.locator('fieldset').nth(1).getByRole('button').first().click();
  await episode.locator('.movie-file-row').first().waitFor();
  await page.goto(`${origin}/mag?boxOffice=world`, { waitUntil: 'domcontentloaded' });
  await page.locator('#world-box-office tbody tr').first().waitFor();
  assert.equal(await page.locator('#world-box-office tbody tr').count(), 30);
  await page.getByRole('tab', { name: 'سینمای ایران', exact: true }).click();
  assert.ok(await page.locator('#iran-box-office').isVisible());
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.goto(`${origin}/music/collections/sousan-collection`, { waitUntil: 'domcontentloaded' });
  await page.getByRole('heading', { name: 'سوسن؛ خاطره‌ها و ریمیکس‌ها', exact: true, level: 1 }).waitFor();
  assert.ok(await page.getByText('با تو چه شب‌ها (ریمیکس)', { exact: false }).count());
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ movieSelection: 'type → quality → matching links', seriesSelection: 'type → quality → matching links', worldRows: 30, sousanCollection: 'visible', mobileOverflow: false, pageErrors: errors }));
} finally { await browser.close(); }
