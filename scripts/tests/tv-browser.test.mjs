import assert from "node:assert/strict";
import test from "node:test";
import { mkdir } from "node:fs/promises";
import { pathToFileURL } from "node:url";

// Explicit opt-in: uses a running dev server, never starts/stops production.
test("TV catalog, typo search, D-pad focus, dialogs and small-screen apps page", { skip: !process.env.TV_TEST_ORIGIN || !process.env.PLAYWRIGHT_MODULE, timeout: 180000 }, async () => {
  const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
  const origin = process.env.TV_TEST_ORIGIN;
  const browser = await chromium.launch({ channel: process.env.TV_TEST_BROWSER || "msedge", headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 }, serviceWorkers: "block" });
  page.setDefaultTimeout(30000);
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  try {
    // Tiny local animated clip; no copyrighted media downloads in UI QA.
    await page.goto("about:blank");
    const clip = Buffer.from(await page.evaluate(async () => {
      const canvas = document.createElement("canvas"); canvas.width = 320; canvas.height = 180;
      const ctx = canvas.getContext("2d");
      const stream = canvas.captureStream(12), recorder = new MediaRecorder(stream, { mimeType: "video/webm;codecs=vp8" });
      const chunks = [];
      const recorded = new Promise(resolve => { recorder.ondataavailable = e => chunks.push(e.data); recorder.onstop = async () => resolve(Array.from(new Uint8Array(await new Blob(chunks).arrayBuffer()))); });
      let frame = 0;
      const timer = setInterval(() => { ctx.fillStyle = "#151b2a"; ctx.fillRect(0, 0, 320, 180); ctx.fillStyle = "#f2d080"; ctx.fillRect((frame++ * 10) % 280, 70, 40, 40); }, 80);
      recorder.start(); await new Promise(resolve => setTimeout(resolve, 2200)); recorder.stop(); clearInterval(timer);
      stream.getTracks().forEach(track => track.stop()); return recorded;
    }));
    await page.route("**/*", async route => {
      if (route.request().resourceType() !== "media") return route.continue();
      const range = route.request().headers().range?.match(/bytes=(\d+)-(\d*)/);
      const start = range ? Number(range[1]) : 0, end = range?.[2] ? Math.min(Number(range[2]), clip.length - 1) : clip.length - 1;
      await route.fulfill({ status: range ? 206 : 200, contentType: "video/webm", headers: { "Accept-Ranges": "bytes", "Content-Length": String(end - start + 1), ...(range ? { "Content-Range": `bytes ${start}-${end}/${clip.length}` } : {}) }, body: clip.subarray(start, end + 1) });
    });
    await mkdir(".media-cache/android-tv/qa", { recursive: true });
    await page.goto(`${origin}/tv`);
    await page.locator('[data-tv-focus="hero-play"]:focus').waitFor();
    assert.equal(await page.locator(".mobile-app-shell,.watch-together-launcher").count(), 0);
    await page.keyboard.press("ArrowLeft");
    assert.equal(await page.evaluate(() => document.activeElement.dataset.tvFocus), "hero-details");
    await page.keyboard.press("ArrowDown");
    assert.ok(await page.evaluate(() => document.activeElement instanceof HTMLAnchorElement));
    await page.screenshot({ path: ".media-cache/android-tv/qa/home-720.png" });
    await page.goto(`${origin}/tv/search`);
    const input = page.getByRole("textbox");
    await page.getByRole("button", { name: "صفحه‌کلید ریموت", exact: true }).click();
    await page.locator("dialog[open] .tv-keyboard").waitFor();
    assert.ok(await page.locator("dialog[open] .tv-key-row button").evaluateAll(buttons => buttons.every(button => button.getBoundingClientRect().width >= 48)), "remote keys are adequately spaced");
    await page.keyboard.press("Escape");
    await input.fill("breakng bud");
    await page.waitForResponse(response => response.url().includes("/api/tv/search?") && response.url().includes("breakng") && response.ok());
    await page.locator(".tv-grid .tv-card").first().waitFor();
    assert.match(await page.locator(".tv-card").first().getAttribute("href"), /tt0903747/);
    assert.match(await page.locator(".tv-corrections").innerText(), /Breaking Bad/i);
    await input.press("Enter");
    assert.ok(await page.locator(".tv-grid a").first().evaluate(element => element === document.activeElement));
    await page.screenshot({ path: ".media-cache/android-tv/qa/search-720.png" });
    await page.keyboard.press("Enter");
    await page.waitForURL("**/tv/title/tt0903747");
    await page.locator('[data-tv-focus="title-play"]:focus').waitFor();
    assert.ok(await page.locator(".tv-episode-grid button").count());
    await page.screenshot({ path: ".media-cache/android-tv/qa/title-720.png" });
    await page.keyboard.press("Enter");
    await page.waitForURL("**/tv/watch/**");
    await page.locator("[data-tv-player]:focus").waitFor();
    await page.waitForFunction(() => document.querySelector("video")?.readyState >= 2);
    await page.evaluate(() => document.querySelector("video").pause());
    await page.locator('[data-tv-player]').press("Enter");
    await page.waitForFunction(() => document.querySelector("video")?.currentTime > .1);
    await page.keyboard.press("ArrowDown");
    await page.waitForFunction(() => document.querySelector("[data-player-controls] button") === document.activeElement);
    const settings = page.getByRole("button", { name: "تنظیمات", exact: true });
    await settings.click();
    await page.locator("dialog[open]").waitFor();
    await page.keyboard.press("ArrowDown");
    assert.ok(await page.evaluate(() => document.activeElement.closest('dialog[open]') !== null));
    await page.screenshot({ path: ".media-cache/android-tv/qa/player-settings-720.png" });
    await page.keyboard.press("Escape");
    assert.equal(await page.locator("dialog[open]").count(), 0);
    assert.ok(page.url().includes("/tv/watch/"), "Back closes the dialog before leaving playback");
    await page.getByRole("button", { name: "زیرنویس (c)", exact: true }).click();
    await page.locator("dialog[open] [data-subtitle-panel]").waitFor();
    const consumed = await page.evaluate(() => !window.dispatchEvent(new CustomEvent("sarvnema:tv-back", { cancelable: true })));
    assert.equal(consumed, true);
    await page.locator("dialog[open]").waitFor({ state: "detached" });
    await page.setViewportSize({ width: 1920, height: 1080 });
    await page.goto(`${origin}/tv`);
    await page.locator('.tv-main [data-tv-focus]:focus').waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: ".media-cache/android-tv/qa/home-1080.png" });
    await page.goto(`${origin}/tv/search`);
    await page.waitForFunction(() => document.querySelector('.tv-search-input input')?.value === "breakng bud");
    await page.goto(`${origin}/tv/watch/tt33184638`);
    await page.getByRole("heading", { level: 2 }).waitFor();
    assert.equal(await page.locator("video").count(), 0, "copyright-disabled titles cannot play through the TV route");
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`${origin}/apps`);
    await page.getByRole("heading", { level: 1 }).waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "applications page fits a phone");
    assert.equal(await page.locator('html[data-tv]').count(), 0);
    await page.screenshot({ path: ".media-cache/android-tv/qa/apps-mobile.png", fullPage: true });
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
